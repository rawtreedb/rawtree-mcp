import { z } from 'zod';
import type { RawTreeScope } from '../client.js';
import type { JsonObject, JsonValue } from '../types.js';

export interface ToolScopeOptions {
  requireExplicitScope?: boolean;
}

export const s3StorageInput = z.strictObject({
  dataBucket: z
    .string()
    .min(3)
    .max(63)
    .describe('Customer-owned S3 data bucket.'),
  dataPath: z.string().optional().describe('Optional data object-key prefix.'),
  backupBucket: z
    .string()
    .min(3)
    .max(63)
    .describe('Customer-owned S3 backup bucket.'),
  backupPath: z
    .string()
    .optional()
    .describe('Optional backup object-key prefix.'),
  roleArn: z
    .string()
    .min(1)
    .describe('ARN of the customer IAM role RawTree may assume.'),
});

export const externalIdInput = z
  .string()
  .min(2)
  .max(1224)
  .regex(/^[A-Za-z0-9_+=,.@:/-]+$/)
  .describe(
    'Immutable cluster External ID. Use this exact value in customer IAM role trust policies.',
  );

export const resourceTagInput = z
  .string()
  .min(1)
  .max(256)
  .regex(/^[a-z0-9][a-z0-9-]*$/)
  .describe(
    'Immutable value of the rawtree.com/cluster AWS resource tag on eligible customer buckets and IAM roles.',
  );

function scopeName(options: ToolScopeOptions, description: string) {
  const schema = z.string().min(1).describe(description);
  return options.requireExplicitScope ? schema : schema.optional();
}

export function clusterScopeInput(options: ToolScopeOptions) {
  return {
    organization: scopeName(
      options,
      'RawTree organization containing the target cluster.',
    ),
    cluster: scopeName(options, 'RawTree cluster to use for this operation.'),
  };
}

export function organizationScopeInput(options: ToolScopeOptions) {
  return {
    organization: scopeName(
      options,
      'RawTree organization containing the target database.',
    ),
  };
}

export function databaseScopeInput(options: ToolScopeOptions) {
  return {
    ...clusterScopeInput(options),
    database: z
      .string()
      .min(1)
      .optional()
      .describe(
        'Optional RawTree database override. RawTree uses the default database when omitted.',
      ),
  };
}

export function requestScope({
  organization,
  cluster,
  database,
}: RawTreeScope): RawTreeScope {
  return { organization, cluster, database };
}

export function textResult(...texts: string[]) {
  return {
    content: texts.map((text) => ({ type: 'text' as const, text })),
  };
}

export function jsonResult(value: unknown, label?: string) {
  const body = JSON.stringify(value, null, 2);
  return textResult(label ? `${label}\n${body}` : body);
}

export function namedJsonResult(name: string, value: unknown) {
  return textResult(`${name}:\n${JSON.stringify(value, null, 2)}`);
}

function isPlainObject(value: unknown): value is Record<string, unknown> {
  return (
    typeof value === 'object' &&
    value !== null &&
    !Array.isArray(value) &&
    Object.getPrototypeOf(value) === Object.prototype
  );
}

export function isJsonValue(value: unknown): value is JsonValue {
  if (
    value === null ||
    typeof value === 'string' ||
    typeof value === 'number' ||
    typeof value === 'boolean'
  ) {
    return Number.isFinite(value) || typeof value !== 'number';
  }

  if (Array.isArray(value)) return value.every(isJsonValue);

  if (!isPlainObject(value)) return false;

  return Object.values(value).every(isJsonValue);
}

export function asJsonRows(value: unknown): JsonObject | JsonObject[] {
  if (isPlainObject(value) && isJsonValue(value)) return value;

  if (
    Array.isArray(value) &&
    value.length > 0 &&
    value.every((item) => isPlainObject(item) && isJsonValue(item))
  ) {
    return value;
  }

  throw new Error(
    'data must be a JSON object or a non-empty array of JSON objects.',
  );
}

export const s3StorageAccessInput = z.strictObject({
  externalId: externalIdInput
    .optional()
    .describe(
      'Immutable S3 storage External ID. The API generates it when omitted for managed storage; required for custom storage.',
    ),
  resourceTag: resourceTagInput
    .optional()
    .describe(
      'Immutable rawtree.com/cluster tag value for S3 storage access. Generated by the API when omitted.',
    ),
});
